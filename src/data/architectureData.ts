export type LayerId =
  | 'ui'
  | 'orchestration'
  | 'runtime'
  | 'data'
  | 'integrations'
  | 'organization';

export type ConnectionType = 'primary' | 'bidirectional' | 'secondary' | 'persistence';

export type NodeStatus = 'Implemented' | 'In Development' | 'Planned' | 'Proposed';

export type NodeType =
  | 'user'
  | 'agent'
  | 'runtime'
  | 'data'
  | 'model'
  | 'tool'
  | 'security'
  | 'workspace'
  | 'orchestrator';

export interface ArchSubsystemSection {
  title: string;
  items: string[];
}

export interface ArchNode {
  id: string;
  layerId: LayerId;
  title: string;
  subtitle: string;
  description: string;
  purpose: string;
  responsibilities: string[];
  inputs: string[];
  outputs: string[];
  related: string[]; // node IDs
  icon: string; // Lucide icon name
  status: NodeStatus;
  nodeType: NodeType;
  docSlug?: string;
  docTitle?: string;
  subsystems?: ArchSubsystemSection[];
  colSpan?: number;
  agentCategory?: 'core' | 'quality' | 'delivery' | 'data';
}

export interface ArchConnection {
  id: string;
  source: string;
  target: string;
  type: ConnectionType;
  label?: string;
  purpose?: string;
  dataPayload?: string[];
}

export interface LayerColorTokens {
  accent: string;       // icon / border / badge text color
  bg: string;           // container background
  badge: string;        // label badge bg
  badgeText: string;    // label badge text
  glow: string;         // box-shadow glow (CSS value)
  nodeAccent: string;   // node left-border color
  nodeBg: string;       // node background
}

export interface ArchLayer {
  id: LayerId;
  title: string;
  subtitle: string;
  color: LayerColorTokens;       // dark theme tokens
  lightColor: LayerColorTokens;  // light theme tokens
}

export interface PresetView {
  id: 'overview' | 'agent-flow' | 'execution' | 'model-flow' | 'data-flow' | 'security';
  label: string;
  description: string;
  badge?: string;
  highlightNodes: string[];
  highlightConnections: string[];
}

